const STEMS = '甲乙丙丁戊己庚辛壬癸';
const BRANCHES = '子丑寅卯辰巳午未申酉戌亥';

// Sexagenary year (干支) for a Gregorian date. The year turns at 立春 (about 4 February),
// which is how painters dated their work.
export function ganzhiYear(date) {
  let y = date.getFullYear();
  if (date.getMonth() === 0 || (date.getMonth() === 1 && date.getDate() < 4)) y -= 1;
  const i = (((y - 4) % 60) + 60) % 60;
  return STEMS[i % 10] + BRANCHES[i % 12];
}

// Season by the four "beginnings" (立春, 立夏, 立秋, 立冬), approximately.
export function seasonIndex(date) {
  const md = (date.getMonth() + 1) * 100 + date.getDate();
  if (md >= 204 && md < 505) return 0;
  if (md >= 505 && md < 807) return 1;
  if (md >= 807 && md < 1107) return 2;
  return 3;
}

export function dateLine(lang, date = new Date()) {
  if (lang === 'zh') return `${ganzhiYear(date)}${'春夏秋冬'[seasonIndex(date)]}日`;
  return `${['Spring', 'Summer', 'Autumn', 'Winter'][seasonIndex(date)]} ${date.getFullYear()}`;
}
